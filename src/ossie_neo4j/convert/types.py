"""How Neo4j property types and Ossie value concepts map onto each other.

Going to Ossie, the element type of a Neo4j property type picks the value concept that plays the
value role. Five element types map exactly to a built-in concept: STRING, INTEGER, FLOAT,
BOOLEAN and DATE, plus LOCAL DATETIME to ``DateTime``.

Every other type gets a *generated* ValueType named ``Neo4j<Type>``. It extends the nearest
built-in and carries ``neo4j:type`` in its annotations, so the exact type is kept natively in
Ossie and can be recovered. ``INTEGER32`` is one example; it becomes ``Neo4jInteger32``, which
extends ``Integer``.

``LIST<X>`` has no value concept of its own. It is the relationship to ``X``'s concept, written
without a multiplicity, which is how Ossie expresses a multi-valued attribute.
"""

from __future__ import annotations

from ..ogs.models import Neo4jType as T
from ..ossie.models import ConceptType
from .naming import pascal

GENERATED = "neo4j:generated"
TYPE_ANNOTATION = "neo4j:type"

EXACT: dict[T, str] = {
    T.STRING: "String",
    T.INTEGER: "Integer",
    T.FLOAT: "Float",
    T.BOOLEAN: "Boolean",
    T.DATE: "Date",
    T.LOCAL_DATETIME: "DateTime",
}

# The built-in each generated value type extends. Opaque types (points, durations, vectors and so
# on) extend String, because Ossie has no closer built-in.
_GENERATED_BASE: dict[T, str] = {
    T.INTEGER32: "Integer",
    T.INTEGER16: "Integer",
    T.INTEGER8: "Integer",
    T.FLOAT32: "Float",
    T.ZONED_DATETIME: "DateTime",
    T.LOCAL_TIME: "String",
    T.ZONED_TIME: "String",
    T.DURATION: "String",
    T.POINT: "String",
    T.UUID: "String",
    T.ANY: "String",
}

# The reverse direction, from a built-in concept. Ossie's Decimal is exact; Neo4j has no exact
# decimal type, so it becomes FLOAT, and the caller reports that as approximated.
FROM_BUILTIN: dict[str, T] = {v: k for k, v in EXACT.items()} | {"Decimal": T.FLOAT}
APPROXIMATE_BUILTINS = {"Decimal"}


def element_concept(t: T) -> tuple[str, dict | None]:
    """The value concept for one value of type ``t`` (the element type, for LIST).

    Returns ``(concept_name, generated_definition_or_None)``.
    """
    elem = t.element if t.is_list else t
    if elem in EXACT:
        return EXACT[elem], None
    name = "Neo4j" + pascal(elem.value.replace("<", " ").replace(">", ""))
    base = _GENERATED_BASE.get(elem, "String")  # vectors are opaque
    definition = {
        "concept": name,
        "type": ConceptType.VALUE_TYPE.value,
        "description": f"Neo4j {elem.value} value, generated by ossie-neo4j.",
        "extends": [base],
        "annotations": {GENERATED: True, TYPE_ANNOTATION: elem.value},
    }
    return name, definition


def list_of(elem: T) -> T | None:
    """``LIST<elem>``, if Neo4j has that type. UUID and vector types have no list form."""
    try:
        return T(f"LIST<{elem.value}>")
    except ValueError:
        return None


def _all_generated() -> dict[str, dict]:
    out = {}
    for t in T:
        if t.is_list or t in EXACT:
            continue
        name, definition = element_concept(t)
        out[name] = definition
    return out


ALL_GENERATED: dict[str, dict] = _all_generated()


def is_generated(definition: dict) -> bool:
    return bool((definition.get("annotations") or {}).get(GENERATED))


def resolve(concept: str, value_types: dict[str, dict]) -> tuple[T | None, bool]:
    """The Neo4j element type for a value concept, following ``extends`` breadth-first.

    ``value_types`` maps names to ValueType definitions (plain dicts). Generated ``Neo4j*``
    concepts resolve even when they are not listed there. Returns ``(type, approximated)``. The
    type is None if the concept never reaches a built-in or generated type.
    """
    seen: set[str] = set()
    todo = [concept]
    while todo:
        c = todo.pop(0)
        if c in seen:
            continue
        seen.add(c)
        d = value_types.get(c) or ALL_GENERATED.get(c)
        if d is not None and is_generated(d):
            return T(d["annotations"][TYPE_ANNOTATION]), False
        if c in FROM_BUILTIN:
            return FROM_BUILTIN[c], c in APPROXIMATE_BUILTINS
        if d is not None:
            todo.extend(d.get("extends") or [])
    return None, True


def element(t: T | None) -> T:
    """The element type of ``t``, with an untyped property treated as ANY."""
    if t is None:
        return T.ANY
    return t.element if t.is_list else t


# --- semantic model datatypes (phase 2) ------------------------------------------------------
#
# Ossie fields carry a logical ``datatype``. OGS table columns carry a source ``type`` (free
# text, e.g. VARCHAR) and a ``suggested`` Neo4j type. The two are mapped through ``suggested``.

DATATYPE_FOR: dict[T, str] = {
    T.STRING: "String",
    T.INTEGER: "Integer",
    T.INTEGER32: "Integer",
    T.INTEGER16: "Integer",
    T.INTEGER8: "Integer",
    T.FLOAT: "Float",
    T.FLOAT32: "Float",
    T.BOOLEAN: "Boolean",
    T.DATE: "Date",
    T.LOCAL_TIME: "Time",
    T.ZONED_TIME: "Time",
    T.LOCAL_DATETIME: "DateTime",
    T.ZONED_DATETIME: "DateTimeTz",
}
"""Neo4j type ➜ Ossie datatype. Anything not listed (lists, vectors, points, ...) is Opaque."""

NEO4J_FOR_DATATYPE: dict[str, T | None] = {
    "String": T.STRING,
    "Integer": T.INTEGER,
    "Decimal": T.FLOAT,  # approximated: Neo4j has no exact decimal
    "Float": T.FLOAT,
    "Boolean": T.BOOLEAN,
    "Date": T.DATE,
    "Time": T.LOCAL_TIME,
    "DateTime": T.LOCAL_DATETIME,
    "DateTimeTz": T.ZONED_DATETIME,
    "Opaque": None,
}
"""Ossie datatype ➜ the Neo4j type suggested for a column."""


def datatype_for(t: T | str | None) -> str | None:
    if t is None:
        return None
    return DATATYPE_FOR.get(T(t), "Opaque")


_SOURCE_TYPES: list[tuple[tuple[str, ...], str]] = [
    (("TIMESTAMP_TZ", "TIMESTAMPTZ", "TIMESTAMP WITH TIME ZONE", "DATETIMEOFFSET"), "DateTimeTz"),
    (("TIMESTAMP", "DATETIME", "SMALLDATETIME"), "DateTime"),
    (("DATE",), "Date"),
    (("TIME",), "Time"),
    (("BOOL", "BIT"), "Boolean"),
    (("DECIMAL", "NUMERIC", "NUMBER", "MONEY", "DEC"), "Decimal"),
    (("DOUBLE", "FLOAT", "REAL"), "Float"),
    (("INT", "BIGINT", "SMALLINT", "TINYINT", "MEDIUMINT", "SERIAL", "BIGSERIAL"), "Integer"),
    (("CHAR", "VARCHAR", "NVARCHAR", "NCHAR", "TEXT", "STRING", "CLOB", "UUID"), "String"),
]


def datatype_from_source(source_type: str | None) -> str | None:
    """A best-effort Ossie datatype from a column's source type name (e.g. ``VARCHAR(20)``)."""
    if not source_type:
        return None
    s = source_type.upper()
    if s.startswith("INTERVAL"):  # not an integer, despite the prefix
        return None
    for needles, datatype in _SOURCE_TYPES:
        if s.startswith(needles):
            return datatype
    return None
